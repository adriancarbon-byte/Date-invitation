import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root=new URL('../dist/',import.meta.url);
assert.deepEqual((await readdir(root)).sort(),['_headers','index.html']);
const html=await readFile(new URL('index.html',root),'utf8');
const headers=await readFile(new URL('_headers',root),'utf8');
const policy=html.match(/http-equiv="Content-Security-Policy" content="([^"]+)"/)?.[1];
assert.ok(policy,'Production CSP is missing');
const scripts=[...html.matchAll(/<script type="module">([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1);
const digest=createHash('sha256').update(scripts[0][1]).digest('base64');
assert.ok(policy.includes(`script-src 'sha256-${digest}' data:`),'Script CSP hash is stale');
assert.ok(policy.includes("connect-src 'self' https://api.web3forms.com"),'Email provider is blocked by CSP');
assert.ok(headers.includes(`Content-Security-Policy: ${policy}; frame-ancestors 'none'`));
assert.ok(headers.includes('X-Frame-Options: DENY'));
assert.ok(headers.includes('X-Robots-Tag: noindex, nofollow, noarchive'));
assert.ok(!html.includes('WEB3FORMS_ACCESS_KEY'),'Runtime configuration leaked into static output');
assert.ok(!/\b(?:src|href)="\.\/assets\//.test(html),'Production assets are missing');
assert.ok(!/\son[a-z]+\s*=/i.test(html),'Unexpected inline event handler');
console.log('Release checks passed: CSP hashes, provider access, headers, self-contained assets and output allowlist.');
